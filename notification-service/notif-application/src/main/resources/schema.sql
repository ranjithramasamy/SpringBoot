CREATE TABLE CA_TRANSFORMATION_PROFILE (
    PROFILE_ID        VARCHAR2(36)  PRIMARY KEY,
    MESSAGE_TYPE      VARCHAR2(32)  NOT NULL,
    MESSAGE_VERSION   VARCHAR2(16)  NOT NULL,
    TARGET_ISO_TYPE   VARCHAR2(32)  NOT NULL,
    MAPPING_S3_KEY    VARCHAR2(256) NOT NULL,
    RULES_S3_KEY      VARCHAR2(256) NOT NULL,
    XSD_S3_KEY        VARCHAR2(256) NOT NULL,
    ACTIVE_FLAG       NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT UK_PROFILE_TYPE_VER UNIQUE (MESSAGE_TYPE, MESSAGE_VERSION)
);

CREATE TABLE CA_TRANSFORMATION_AUDIT (
    AUDIT_ID          VARCHAR2(36)  PRIMARY KEY,
    MESSAGE_ID        VARCHAR2(64)  NOT NULL,
    EVENT_ID          VARCHAR2(64)  NOT NULL,
    MESSAGE_TYPE      VARCHAR2(32)  NOT NULL,
    PROFILE_ID        VARCHAR2(36),
    STATUS            VARCHAR2(24)  NOT NULL,
    ERROR_REASON      VARCHAR2(1000),
    CREATED_AT        TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UK_AUDIT_MSG_ID UNIQUE (MESSAGE_ID)
);

CREATE INDEX IDX_AUDIT_EVENT_ID ON CA_TRANSFORMATION_AUDIT (EVENT_ID);
